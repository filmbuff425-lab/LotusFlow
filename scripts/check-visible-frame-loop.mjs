import assert from 'node:assert/strict';
import {createVisibleFrameLoop} from '../dist/visible-frame-loop.js';
const frames=new Map(),events=new Map();let next=0,active=true,updates=0,pauses=0,mutation;
globalThis.requestAnimationFrame=callback=>{frames.set(++next,callback);return next};
globalThis.cancelAnimationFrame=id=>frames.delete(id);
globalThis.document={body:{},addEventListener:(name,fn)=>events.set(name,fn),removeEventListener:name=>events.delete(name)};
globalThis.addEventListener=(name,fn)=>events.set(name,fn);
globalThis.removeEventListener=name=>events.delete(name);
globalThis.MutationObserver=class{constructor(fn){mutation=fn}observe(){}disconnect(){mutation=null}};
const loop=createVisibleFrameLoop({update:()=>updates++,active:()=>active,onPause:()=>pauses++,watchBodyClasses:true});
const step=()=>{const [[id,callback]]=frames;frames.delete(id);callback(16)};
loop.wake();loop.wake();assert.equal(frames.size,1,'Wake events cannot create duplicate render loops');
step();assert.equal(updates,1);assert.equal(frames.size,1);
active=false;step();assert.equal(updates,1);assert.equal(frames.size,0,'Offscreen scenes stop scheduling callbacks');
active=true;loop.wake();step();assert.equal(updates,2);
active=false;events.get('visibilitychange')();assert.equal(frames.size,0,'Background tabs cancel pending work immediately');
active=true;events.get('pageshow')();assert.equal(frames.size,1,'Returning to a page resumes its existing scene');
active=false;mutation();assert.equal(frames.size,0,'Opening the studio computer pauses the covered 3D scene');
active=true;mutation();assert.equal(frames.size,1,'Closing the computer resumes the same scene');
loop.dispose();loop.wake();assert.equal(frames.size,0);assert.equal(events.size,0);assert.equal(mutation,null);assert.ok(pauses>=3);
console.log('Visibility checks passed: a single render loop, no hidden work, and correct resume behavior.');
